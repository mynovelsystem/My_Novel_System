const I18N_DICTS = {
  es: { ...FALLBACK_DICTS.es },
  en: { ...FALLBACK_DICTS.en }
};

let currentLang = "es";
let i18nLoadedPromise = null;

function detectDefaultLanguage() {
  try {
    const uiLang = (chrome.i18n && chrome.i18n.getUILanguage ? chrome.i18n.getUILanguage() : navigator.language) || "es";
    return uiLang.toLowerCase().startsWith("en") ? "en" : "es";
  } catch {
    return "es";
  }
}

async function initI18n(forcedLang) {
  if (!i18nLoadedPromise) {
    i18nLoadedPromise = Promise.all([
      fetch(chrome.runtime.getURL("locales/es.json")).then((r) => r.json()).catch(() => ({})),
      fetch(chrome.runtime.getURL("locales/en.json")).then((r) => r.json()).catch(() => ({}))
    ]).then(([esDict, enDict]) => {
      I18N_DICTS.es = { ...FALLBACK_DICTS.es, ...(esDict || {}) };
      I18N_DICTS.en = { ...FALLBACK_DICTS.en, ...(enDict || {}) };
    });
  }
  await i18nLoadedPromise;

  if (forcedLang === "es" || forcedLang === "en") {
    currentLang = forcedLang;
    return currentLang;
  }

  try {
    const { settings } = await chrome.storage.local.get(["settings"]);
    if (settings && (settings.language === "es" || settings.language === "en")) {
      currentLang = settings.language;
    } else {
      currentLang = detectDefaultLanguage();
    }
  } catch {
    currentLang = detectDefaultLanguage();
  }
  return currentLang;
}

function setCurrentLang(lang) {
  if (lang === "es" || lang === "en") {
    currentLang = lang;
  }
}

function getCurrentLang() {
  return currentLang;
}

function t(key, vars = {}) {
  const dict = I18N_DICTS[currentLang] || I18N_DICTS.es || {};
  const fallbackDict = I18N_DICTS.es || {};
  let template = dict[key] !== undefined ? dict[key] : (fallbackDict[key] !== undefined ? fallbackDict[key] : key);
  return String(template).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

function applyI18nToDom(root = document) {
  if (!root || !root.querySelectorAll) return;

  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });

  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });

  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key));
  });
}